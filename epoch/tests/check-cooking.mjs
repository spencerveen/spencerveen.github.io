import assert from "node:assert/strict";
import {GameState} from "../js/state.js";
import {LEGACY_HOME} from "../js/stockpile.js";
import {FOOD_EFFECTS} from "../js/survival.js";
import {prepareCooking,COOKING_RECIPES} from "../js/cooking.js";
const mem=new Map();
globalThis.localStorage={getItem:k=>mem.get(k)||null,setItem:(k,v)=>mem.set(k,v),removeItem:k=>mem.delete(k)};
const game=new GameState({slot:1,newGame:true});
game.onChange=()=>{};
const sx=LEGACY_HOME.x,sz=LEGACY_HOME.z;
assert(game.foundStockpile(sx,sz));
const hx=sx+4,hz=sz+4;
game.data.village.buildings.push({id:"building_1",kind:"hearth",x:hx,z:hz,turn:0});
game.data.inventory[0]={id:"animal_meat",qty:3};
game.data.inventory[1]={id:"berries",qty:2};
game.data.village.stockpile.items.wood=2;
assert.equal(game.cookingPreview("roasted_meat",hx,hz).ok,false,"requires fire discovery");
game.data.technologies.push("fire");
assert.equal(game.cookingPreview("roasted_meat",0,500).ok,false,"no remote hearth access");
assert.equal(game.cookingPreview("roasted_meat",hx,hz).ok,true);
const first=game.cookRecipe("roasted_meat",hx,hz);
assert.equal(first.ok,true);
assert.equal(first.qty,2);
assert.equal(game.inventoryCount("animal_meat"),1);
assert.equal(game.inventoryCount("cooked_meat"),2);
assert.equal(game.data.village.stockpile.items.wood,1);
assert(game.data.skills.cooking>0);
const second=game.cookRecipe("berry_roast",hx,hz);
assert(second.ok);
assert.equal(game.inventoryCount("berry_roast"),1);
assert.equal(game.inventoryCount("animal_meat"),0);
assert.equal(game.inventoryCount("berries"),0);
assert.equal(game.data.village.stockpile.items.wood,0);
assert.equal(game.cookingPreview("roasted_meat",hx,hz).ok,false);
const previous=JSON.stringify(game.data.inventory);
assert.equal(game.cookRecipe("roasted_meat",hx,hz).ok,false);
assert.equal(JSON.stringify(game.data.inventory),previous,"missing inputs cannot consume supplies");
game.data.survival.hunger=20;game.data.survival.stamina=20;game.data.survival.health=70;
assert.equal(game.quickEat(),"berry_roast","E prefers berry-roasted meals");
assert.equal(game.inventoryCount("berry_roast"),0);
assert.equal(game.data.survival.hunger,72);
assert.equal(game.data.survival.stamina,40);
assert.equal(game.data.survival.health,80);
assert.equal(game.survivalStatus().maxStamina,120);
assert.equal(game.quickEat(),"cooked_meat");
assert.equal(game.inventoryCount("cooked_meat"),1);
assert.equal(game.data.survival.hunger,100);
assert.equal(game.data.survival.health,86);
assert(!game.eatFood("animal_meat"));
game.save();
const saved=new GameState({slot:1});
assert.equal(saved.inventoryCount("cooked_meat"),1);
assert.equal(saved.data.village.stockpile.items.wood,0);
assert.equal(saved.survivalStatus().maxStamina,120);
assert(saved.data.skills.cooking>0);
assert.deepEqual(Object.keys(COOKING_RECIPES),["roasted_meat","berry_roast","cooked_fish"]);
assert(FOOD_EFFECTS.cooked_meat.hunger<FOOD_EFFECTS.berry_roast.hunger);
const full=new GameState({slot:2,newGame:true});
full.onChange=()=>{};
assert(full.foundStockpile(sx,sz));
full.data.technologies.push("fire");
full.data.village.buildings.push({id:"building_1",kind:"hearth",x:hx,z:hz,turn:0});
full.data.inventory=Array.from({length:10},()=>({id:"stone",qty:12}));
full.data.inventory[0]={id:"animal_meat",qty:12};
full.data.village.stockpile.items.wood=5;
const before=JSON.stringify(full.data);
const fail=full.cookRecipe("roasted_meat",hx,hz);
assert(!fail.ok&&/backpack full/i.test(fail.reason));
assert.equal(JSON.stringify(full.data),before,"full pack must never consume fuel or ingredients");
full.data.inventory[1]=null;
assert(full.cookRecipe("roasted_meat",hx,hz).ok,"a free slot permits cooking");
assert.equal(full.data.village.stockpile.items.wood,4);
assert.equal(full.inventoryCount("cooked_meat"),2);
const stored=new GameState({slot:3,newGame:true});
stored.onChange=()=>{};
assert(stored.foundStockpile(sx,sz));
stored.data.technologies.push("fire");
stored.data.village.buildings.push({id:"building_1",kind:"hearth",x:hx,z:hz,turn:0});
stored.data.village.stockpile.items.wood=1;
stored.data.village.stockpile.items.animal_meat=2;
assert(stored.cookRecipe("roasted_meat",hx,hz).ok,"stockpile-supplied ingredients work");
assert.equal(stored.data.village.stockpile.items.wood,0);
assert.equal(stored.data.village.stockpile.items.animal_meat,0);
assert.equal(stored.inventoryCount("cooked_meat"),2);
const unbuilt=new GameState({slot:3,newGame:true});
unbuilt.data.technologies.push("fire");
assert(!unbuilt.cookRecipe("roasted_meat",hx,hz).ok);
console.log("PASS cooking: hearth and research gating, raw/cooked food, fuel, mixed supplies, full-pack atomicity, nutrition, E priority and saves");
