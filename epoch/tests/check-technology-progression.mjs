import assert from "node:assert/strict";
import {GameState,KNOWLEDGE_REWARDS,RESEARCH_SECONDS_PER_KNOWLEDGE} from "../js/state.js";
import {LEGACY_HOME} from "../js/stockpile.js";

const store=new Map();
globalThis.localStorage={getItem:k=>store.get(k)||null,setItem:(k,v)=>store.set(k,v),removeItem:k=>store.delete(k)};
const world={groundY:()=>.2,obstacles:[],player:{position:{...LEGACY_HOME}}};
const game=new GameState({slot:1,newGame:true});
game.onChange=()=>{};
assert.equal(RESEARCH_SECONDS_PER_KNOWLEDGE,60);
assert.equal(game.data.knowledge,0);
assert.equal(game.data.village.population,1,"founder starts alone");
assert.equal(game.researchRate(),0,"no passive research without a shelter");
game.gather("wood");game.gather("stone");game.gather("food");
assert.equal(game.data.knowledge,0,"gathering grants skill XP without Knowledge");
assert.equal(game.data.culture,1,"temporary Culture gain stays unchanged");
assert(game.data.skills.woodcutting>0);
assert(game.foundStockpile(LEGACY_HOME.x,LEGACY_HOME.z));
assert.equal(game.data.knowledge,KNOWLEDGE_REWARDS.stockpile);
assert.equal(game.data.village.population,1,"founding creates no villagers");
assert.equal(game.researchRate(),0);
game.data.village.stockpile.items={wood:120,stone:120,berries:10,vines:0};
assert(game.placeVillageBuilding("lore",-10,4,0,world).ok);
assert.equal(game.data.knowledge,9,"first Toolmaker's Shelter adds six Knowledge");
assert.equal(game.researchRate(),1);
for(let i=0;i<59;i++)game.advance(1);
assert.equal(game.data.knowledge,9,"research does not award early points");
game.advance(1);
assert.equal(game.data.knowledge,10,"shelter generates one Knowledge per active minute");
assert.equal(game.data.researchSeconds,0);
assert(game.placeVillageBuilding("family",12,-10,0,world).ok);
assert.equal(game.data.knowledge,13,"first Family Hut rewards the first unique build");
assert.equal(game.data.village.population,1,"housing adds capacity, never new residents");
assert(game.placeVillageBuilding("family",4,6,0,world).ok);
assert.equal(game.data.knowledge,16,"three-building milestone adds Knowledge");
assert(game.placeVillageBuilding("family",12,6,0,world).ok);
assert.equal(game.data.knowledge,16,"repeated huts do not duplicate first-time rewards");
game.save();
const loaded=new GameState({slot:1});
assert.equal(loaded.data.knowledge,16);
assert.equal(loaded.data.village.population,1);
assert.equal(loaded.data.knowledgeClaims.filter(k=>k==="first:family").length,1);
for(let i=0;i<30;i++)loaded.advance(1);
assert.equal(loaded.data.knowledge,16,"partial research does not award early points");
loaded.save();
const again=new GameState({slot:1});
assert.equal(again.data.researchSeconds,30,"partial research progress survives reload");
for(let i=0;i<30;i++)again.advance(1);
assert.equal(again.data.knowledge,17,"shelter research resumes after reload");
assert(again.unlock("tech","fire"),"civilization progress funds the first discovery");
const current=again.data.knowledge;
assert.equal(again.unlock("tech","fire"),false,"a discovered technology cannot be purchased twice");
assert.equal(again.data.knowledge,current);
const veteranSave={version:1,hero:{name:"Veteran"},knowledge:23,village:{
 population:5,stockpile:{x:0,z:8,items:{}},buildings:[{id:"old_lore",kind:"lore",x:4,z:8,turn:0}]
}};
store.set("epoch.stoneage.slot.2",JSON.stringify(veteranSave));
const veteran=new GameState({slot:2});
assert.equal(veteran.data.village.population,5,"older villages retain saved residents");
assert.equal(veteran.data.knowledge,23,"older saves receive no retroactive construction windfall");
assert(veteran.data.knowledgeClaims.includes("first:lore"));
assert(veteran.data.knowledgeClaims.includes("stockpile"));
assert.equal(veteran.researchRate(),1,"old research buildings generate passive Knowledge");
assert.equal(veteran.awardKnowledge("first:lore",6),0,"legacy first-build milestone is not claimable again");
const lone=new GameState({slot:3,newGame:true});
lone.gainXP("crafting",28);
assert.equal(lone.data.knowledge,0,"skill XP never gives Knowledge");
for(let i=0;i<120;i++)lone.advance(1);
assert.equal(lone.data.knowledge,0,"a character without a village cannot produce passive research");
console.log("PASS technology: construction knowledge, milestone deduplication, working research shelter, solo founder, save migration");
