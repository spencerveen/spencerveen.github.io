import assert from "node:assert/strict";
import {GameState} from "../js/state.js";
import {inventoryPanel,handlePackAction} from "../js/inventory-ui.js";
import {villagePanel,handleVillageAction} from "../js/village-ui.js";
import {LEGACY_HOME} from "../js/stockpile.js";
import {ITEMS} from "../js/inventory.js";
const memory=new Map();
globalThis.localStorage={getItem:k=>memory.get(k)||null,setItem:(k,v)=>memory.set(k,v),removeItem:k=>memory.delete(k)};
const game=new GameState({slot:1,newGame:true});
let renders=0;const toasts=[];
const ui={state:game,selectedSlot:null,render(){renders++},toast:m=>toasts.push(m)};
game.onChange=()=>ui.render();
game.addResource("wood",5);game.addResource("berries",3);game.addResource("stone",2);
const woodIndex=game.data.inventory.findIndex(s=>s?.id==="wood");
const berryIndex=game.data.inventory.findIndex(s=>s?.id==="berries");
const stoneIndex=game.data.inventory.findIndex(s=>s?.id==="stone");
const show=()=>inventoryPanel(ui),act=(action,slot)=>handlePackAction(ui,{dataset:{action,slot:String(slot)}});
const initial=show();
assert.equal((initial.match(/data-action="pack-slot"/g)||[]).length,10,"ten slots remain the only item catalog");
assert(initial.includes("3 / 10 slots"),"inventory occupancy is a small, single line");
for(const removed of ["Carried supplies","Inventory space","pack-summary","Food & Survival","Crafting","Craft stone axe","eat-berries","pack-selected"])
 assert(!initial.includes(removed),"remove old inventory section: "+removed);
assert(initial.includes(ITEMS.berries.hint),"hover descriptions are populated from item data");
assert(!initial.includes('role="menu"'),"no floating menu is open initially");
act("pack-slot",berryIndex);
const openBerry=show();
assert(openBerry.includes('role="menu"'),"clicking an item opens its own menu");
assert(openBerry.indexOf('data-action="eat-stack"')<openBerry.indexOf('data-action="drop-stack"'),"Eat appears before Discard");
assert(openBerry.includes('data-slot="'+berryIndex+'"'),"actions target the selected stack");
assert(!openBerry.includes("Berries restore 24 Hunger and 12 Stamina, and temporarily"),"no large food card");
const before=game.survivalStatus().hunger;
game.data.survival.hunger=50;
assert(act("eat-stack",woodIndex),"an invalid menu action is safely ignored");
assert.equal(game.inventoryCount("berries"),3,"cannot eat from the wrong slot");
assert.equal(ui.selectedSlot,berryIndex,"invalid action does not alter selection");
act("eat-stack",berryIndex);
assert.equal(game.inventoryCount("berries"),2,"eating consumes only one selected berry");
assert.equal(game.data.survival.hunger,74);
assert.equal(game.data.survival.foodSeconds,120);
assert.equal(ui.selectedSlot,null,"menu closes after eating");
assert(!show().includes('role="menu"'));
assert(toasts.some(m=>m.startsWith("Ate 1 berry")));
act("pack-slot",woodIndex);
const openWood=show();
assert(!openWood.includes('data-action="eat-stack"'),"wood cannot be eaten");
assert(openWood.includes('data-action="drop-stack"'));
const dropped=game.inventoryCount("wood");
act("drop-stack",woodIndex);
assert.equal(game.inventoryCount("wood"),0,"discard immediately empties the entire chosen stack");
assert.equal(game.inventoryUsed(),2);
assert(toasts.some(m=>m.includes("Discarded "+dropped+" Wood")),"discard shows a compact feedback message");
assert.equal(ui.selectedSlot,null);
act("pack-slot",stoneIndex);
assert.equal(ui.selectedSlot,stoneIndex);
act("pack-slot",stoneIndex);
assert.equal(ui.selectedSlot,null,"clicking an open item closes its menu");
assert(!act("chop-bush",0),"inventory no longer accepts unrelated world actions");
// Village-only crafting: the player must approach the stockpile and use its stored supplies.
assert(game.foundStockpile(LEGACY_HOME.x,LEGACY_HOME.z));
game.data.technologies.push("tools");
const vWorld={player:{position:{x:LEGACY_HOME.x,z:LEGACY_HOME.z}},placingStockpile:false,placingBuilding:null};
const vUi={state:game,world:vWorld,villageSection:"craft",selectedBuildingId:null,render(){renders++},toast:m=>toasts.push(m)};
let craft=villagePanel(vUi);
assert(craft.includes('data-section="craft"'),"Craft is a village section, not an inventory section");
assert(craft.includes('data-action="village-craft-axe"'));
assert(craft.includes("Deposit the required wood and stone"));
assert(!game.craftAxe(LEGACY_HOME.x,LEGACY_HOME.z),"without stockpiled supplies crafting is blocked");
assert(!game.craftAxe(LEGACY_HOME.x+100,LEGACY_HOME.z+100),"remote crafting is blocked");
game.addResource("wood",2);game.addResource("stone",3);
assert(!game.craftAxe(LEGACY_HOME.x,LEGACY_HOME.z),"carried supplies cannot bypass stockpile crafting");
assert.equal(game.depositAllToStockpile(LEGACY_HOME.x,LEGACY_HOME.z),9,"gathered items deposited to stockpile");
const storedBefore={...game.data.village.stockpile.items};
craft=villagePanel(vUi);
assert(craft.includes('data-action="village-craft-axe"'),"craft available at stockpile");
assert(craft.includes("Wood")&&craft.includes("Stone"));
assert(handleVillageAction(vUi,{dataset:{action:"village-craft-axe"}}));
assert.equal(game.data.axe,true,"axe equipped after village crafting");
assert.equal(game.data.village.stockpile.items.wood,storedBefore.wood-2);
assert.equal(game.data.village.stockpile.items.stone,storedBefore.stone-3);
assert(!game.craftAxe(LEGACY_HOME.x,LEGACY_HOME.z),"axe cannot be crafted twice");
assert(villagePanel(vUi).includes("crafted and equipped"));
game.save();
const reloaded=new GameState({slot:1});
assert.equal(reloaded.data.axe,true);
assert.deepEqual(reloaded.data.village.stockpile.items,game.data.village.stockpile.items);
console.log("PASS inventory menus: concise hover info, Eat before Discard, immediate stack removal, no extra cards, village-only stockpiled crafting and save compatibility");
