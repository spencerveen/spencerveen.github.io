import assert from "node:assert/strict";
import {GameState} from "../js/state.js";
import {SURVIVAL,maxStamina,normalizeSurvival} from "../js/survival.js";
import {legacyResidents,normalizeHomes} from "../js/residents.js";
import {STARTER_SEED,forestObjects} from "../js/forest-generation.js";

const memory=new Map();
globalThis.localStorage={getItem:k=>memory.get(k)||null,setItem:(k,v)=>memory.set(k,v),removeItem:k=>memory.delete(k)};
const game=new GameState({slot:1,newGame:true});
game.onChange=()=>{};game.onVitals=()=>{};
assert.deepEqual(game.survivalStatus(),{health:100,stamina:100,hunger:100,foodSeconds:0,gameOver:false,deathCount:0,maxStamina:100});
assert.equal(game.data.village.population,1);
assert.equal(game.data.successorId,null);
assert.equal(game.chooseSuccessor("unknown"),false);
const woodNode=[...Array(3)].flatMap((_,i)=>forestObjects(STARTER_SEED,i-1,0)).find(n=>n.resource==="wood");
assert(woodNode);
game.data.survival.stamina=1;
const beforeHarvest=game.resourceStatus(woodNode);
assert.equal(game.harvestResource(woodNode).type,"exhausted","gathering is blocked when stamina is too low");
assert.equal(game.resourceStatus(woodNode).remaining,beforeHarvest.remaining,"exhaustion never destroys resources");
assert.equal(game.inventoryCount("wood"),0);
game.data.survival.stamina=100;
assert.equal(game.harvestResource(woodNode).type,"gathered");
assert.equal(game.data.survival.stamina,94,"woodcutting costs six stamina");
game.data.survival.stamina=100;
assert.equal(game.spendStamina(6,"sprint"),true);
assert.equal(game.survivalStatus().stamina,94);
game.advance(1);
assert.equal(game.survivalStatus().stamina,94,"sprinting suppresses stamina recovery during the same second");
game.advance(1);
assert.equal(game.survivalStatus().stamina,95,"normal stamina now recovers only one point per second");
game.data.survival.stamina=5;
assert.equal(game.spendStamina(6),false,"insufficient stamina blocks action");
assert.equal(game.data.survival.stamina,5,"blocked action does not remove stamina");
assert.equal(game.spendStamina(5),true);
assert.equal(game.data.survival.stamina,0);
game.advance(1);
assert(game.data.survival.stamina>0,"rest replenishes stamina");
game.data.survival.hunger=0;
game.data.survival.stamina=88;
game.data.survival.health=50;
game.advance(5);
assert.equal(game.data.survival.health,50,"starvation never damages the controlled character");
assert.equal(maxStamina(game.data.survival),SURVIVAL.starvingStaminaMax);
assert(game.data.survival.stamina<=45,"starving clamps max stamina");
game.data.survival.stamina=20;
const before=game.data.survival.stamina;
game.advance(1);
assert(game.data.survival.stamina>before&&game.data.survival.stamina<25,"starving players recover stamina slowly");
const amount=game.addResource("berries",2);
assert.equal(amount,2);
assert(game.eatBerries(),"eating a carried berry restores hunger and energy");
assert.equal(game.inventoryCount("berries"),1);
assert.equal(game.data.survival.hunger,SURVIVAL.berryHunger);
assert.equal(game.data.survival.foodSeconds,SURVIVAL.berryDuration);
assert.equal(maxStamina(game.data.survival),120);
assert(game.data.survival.stamina>before);
game.data.survival.hunger=80;
assert(game.eatBerries(),"eating twice refreshes the food buff without stacking it");
assert.equal(game.data.survival.hunger,100);
assert.equal(game.inventoryCount("berries"),0);
assert.equal(game.data.survival.foodSeconds,120);
assert.equal(game.eatBerries(),false,"cannot eat unavailable food");
game.advance(5);
assert(game.data.survival.foodSeconds<120);
game.data.survival.foodSeconds=1;game.data.survival.stamina=117;
game.advance(2);
assert.equal(game.data.survival.foodSeconds,0);
assert.equal(maxStamina(game.data.survival),100);
assert(game.data.survival.stamina<=100,"expiring food effect clamps temporary extra stamina");
assert.equal(game.swingWeapon(),true,"future weapon swings use the same stamina budget");
game.save();
const persisted=new GameState({slot:1});
assert.equal(persisted.data.survival.hunger,game.data.survival.hunger,"hunger survives reload");
assert.equal(persisted.data.survival.stamina,game.data.survival.stamina,"stamina survives reload");
const migration={version:1,worldSeed:STARTER_SEED,hero:{name:"Legacy"},
 village:{population:5,plots:{},buildings:[]},knowledge:9};
memory.set("epoch.stoneage.slot.2",JSON.stringify(migration));
const old=new GameState({slot:2});
assert.equal(old.survivalStatus().health,100,"old saves gain healthy vitals");
assert.equal(old.data.village.residents.length,4);
const picked=old.data.village.residents[1];
assert(old.chooseSuccessor(picked.id));
assert.equal(old.data.successorId,picked.id);
old.save();
const nominated=new GameState({slot:2});
assert.equal(nominated.data.successorId,picked.id,"successor is persisted by ID");
assert(nominated.damageHero(1000,"a fatal attack"));
assert.equal(nominated.data.survival.gameOver,false);
assert.equal(nominated.data.hero.name,picked.name);
assert.equal(nominated.data.hero.sourceResidentId,picked.id);
assert.equal(nominated.data.survival.health,75);
assert.equal(nominated.data.survival.hunger,80,"successors start with their own hunger instead of inheriting the dead hero's needs");
assert.equal(nominated.data.survival.foodSeconds,0);
assert.equal(nominated.data.generation,2);
assert.equal(nominated.data.village.population,4,"the new leader is no longer counted twice");
assert.equal(nominated.data.village.residents.length,3);
assert.equal(nominated.data.successorId,null,"the consumed nomination clears");
assert.equal(nominated.data.lastDeath.successorName,picked.name);
assert.equal(nominated.data.lastDeath.reason,"a fatal attack");
assert.equal(nominated.data.lineage.at(-1).sourceResidentId,picked.id);
assert.equal(nominated.data.lineage.at(-2).deathReason,"a fatal attack");
const previousDeath=nominated.data.lastDeath.id;
assert(!nominated.heroDies(),"death cannot be processed twice");
const alive=new GameState({slot:2});
assert.equal(alive.data.lastDeath.id,previousDeath);
assert.equal(alive.data.hero.sourceResidentId,picked.id);
assert.equal(alive.data.village.population,4);
assert.equal(alive.chooseSuccessor(null),true);
assert.equal(alive.data.successorId,null);
assert(alive.damageHero(1000,"a forest accident"),"death without a nomination chooses a survivor");
assert.equal(alive.data.generation,3);
assert(alive.data.village.population,3);
assert.equal(alive.data.village.residents.length,2);
assert(alive.data.lineage.at(-1).role,"Chosen by the survivors");
const solo=new GameState({slot:3,newGame:true});
solo.onChange=()=>{};
assert.equal(solo.data.village.population,1);
assert(solo.damageHero(100,"a dangerous fall"));
assert.equal(solo.data.survival.gameOver,true);
assert.equal(solo.data.survival.health,0);
assert.equal(solo.data.village.population,0);
assert.equal(solo.data.lastDeath.gameOver,true);
assert(solo.data.history[0].includes("civilization has ended"));
assert.equal(solo.spendStamina(3),false);
assert.equal(solo.damageHero(20),false);
assert.equal(solo.eatBerries(),false);
const year=solo.data.year,knowledge=solo.data.knowledge;
solo.advance(99999);
assert.equal(solo.data.year,year,"ended games cannot advance time");
assert.equal(solo.data.knowledge,knowledge);
solo.save();
const ended=new GameState({slot:3});
assert.equal(ended.data.village.population,0,"dead saves cannot resurrect an artificial founder");
assert.equal(ended.data.survival.gameOver,true);
assert.equal(ended.data.lastDeath.oldName,solo.data.hero.name);
assert.equal(ended.data.survival.deathCount,1);
assert.equal(ended.chooseSuccessor("unknown"),false);
const malformed=normalizeSurvival({health:999,stamina:-3,hunger:"bad",foodSeconds:999,deathCount:-2,gameOver:false});
assert.equal(malformed.health,100);
assert.equal(malformed.stamina,0);
assert.equal(malformed.hunger,100);
assert.equal(malformed.foodSeconds,120);
console.log("PASS survival: hunger penalties, sprint, stamina, berries, temporary food boost, fatal damage, named and random successors, permadeath, save migration");
