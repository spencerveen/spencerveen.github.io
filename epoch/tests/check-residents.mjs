import assert from "node:assert/strict";
import {GameState} from "../js/state.js";
import {normalizeResidents,legacyResidents,housingUnits,normalizeHomes,moveResidentHome,CAMP_RESIDENT_BEDS} from "../js/residents.js";
import {tribeAtChunk,starterTribeChunk} from "../js/tribes.js";
import {LEGACY_HOME} from "../js/stockpile.js";

const store=new Map();
globalThis.localStorage={getItem:k=>store.get(k)||null,setItem:(k,v)=>store.set(k,v),removeItem:k=>store.delete(k)};
const original=new GameState({slot:1,newGame:true});
original.onChange=()=>{};
assert.equal(original.data.village.population,1);
assert.equal(original.villageHousing().length,1);
assert.equal(original.villageHousing()[0].capacity,CAMP_RESIDENT_BEDS);
assert.equal(original.villageHousing()[0].occupied,0);
assert.equal(original.residentProfile("legacy:resident:0"),null);
const tribe=tribeAtChunk(original.data.worldSeed,...starterTribeChunk(original.data.worldSeed));
assert(original.discoverTribe(tribe));
for(let i=0;i<3;i++){
 const quest=original.tribeProgress(tribe.id).request;
 for(const [id,qty] of Object.entries(quest.cost))assert.equal(original.addResource(id,qty),qty);
 assert(original.aidTribe(tribe.id,i));
}
assert(original.foundStockpile(LEGACY_HOME.x,LEGACY_HOME.z));
original.data.village.stockpile.items={wood:100,stone:100,berries:20,vines:0};
const hut=original.placeVillageBuilding("family",LEGACY_HOME.x+8,LEGACY_HOME.z+10);
assert(hut.ok);
assert(original.inviteTribe(tribe.id));
assert.equal(original.data.village.population,tribe.population+1);
const first=tribe.members[0],second=tribe.members[1];
const profile=original.residentProfile(first.id);
assert(profile);
assert.equal(profile.resident.id,first.id);
assert.equal(profile.resident.name,first.name);
assert.equal(profile.resident.role,"formerLeader");
assert.equal(profile.resident.originTribeName,tribe.name);
assert.equal(profile.resident.memories.length,1);
assert(profile.resident.memories[0].text.includes(tribe.name));
assert.equal(profile.connections.clanmates.length,tribe.population-1,"other recruits share a known tribe history");
assert(profile.connections.clanmates.some(p=>p.id===second.id));
assert.equal(profile.home.label,"Communal camp");
const units=original.villageHousing();
assert.equal(units.length,2);
assert.equal(units.reduce((n,u)=>n+u.occupied,0),tribe.population,"every recruit has exactly one home assignment");
assert.equal(units.reduce((n,u)=>n+u.capacity,0),original.villageCapacity()-1,"founder consumes the remaining camp bed");
assert(!original.assignResidentHome(first.id,"not_a_home"),"unknown homes are rejected");
assert(!original.assignResidentHome(first.id,"camp"),"reassigning to the same home is a no-op");
const family=units.find(u=>u.id===hut.building.id);
assert(family);
const before=original.data.village.population;
assert(original.assignResidentHome(first.id,family.id),"resident may be moved to a hut with a free bed");
assert.equal(original.data.village.population,before);
assert.equal(original.residentProfile(first.id).resident.homeId,family.id);
assert.equal(original.residentProfile(first.id).resident.memories.length,2,"housing changes enter individual history");
assert(original.residentProfile(first.id).connections.housemates.every(p=>p.id!==second.id),"the second recruit still lives elsewhere");
assert(original.assignResidentHome(second.id,family.id),"another villager can move into the same hut");
assert(original.residentProfile(first.id).connections.housemates.some(v=>v.id===second.id),"housemates reflect actual shared housing");
assert.equal(original.residentProfile(first.id).connections.clanmates.length,tribe.population-1,"moving homes does not sever known clan ties");
original.save();
const loaded=new GameState({slot:1});
assert.deepEqual(loaded.data.village.residents,original.data.village.residents,"save/reload keeps identity, homes and memories");
assert.equal(loaded.residentProfile(first.id).home.id,family.id);
assert(loaded.residentProfile(second.id).connections.housemates.some(p=>p.id===first.id),"housemates remain linked after reload");
loaded.nextGeneration();
assert.equal(loaded.data.village.population,before);
assert.equal(loaded.residentProfile(first.id).home.id,family.id,"housing survives succession");
assert.equal(loaded.residentProfile(first.id).connections.clanmates.length,tribe.population-1);
const legacy={version:1,worldSeed:12000,hero:{name:"Legacy"},village:{
 population:5,plots:{},buildings:[{id:"old_family",kind:"family",x:8,z:4,turn:0}],
 stockpile:{x:0,z:8,items:{wood:0,stone:0,berries:0,vines:0}}}};
store.set("epoch.stoneage.slot.2",JSON.stringify(legacy));
const migrated=new GameState({slot:2});
assert.equal(migrated.data.village.residents.length,4);
assert(migrated.data.village.residents.every(v=>v.homeId==="camp"),"existing residents initially belong to camp");
assert.equal(migrated.villageHousing()[0].occupied,4);
assert(migrated.assignResidentHome("legacy:resident:0","old_family"));
assert.equal(migrated.villageHousing()[0].occupied,3);
assert(!migrated.assignResidentHome("legacy:resident:0","invalid"),"invalid housing never changes the roster");
assert(migrated.assignResidentHome("legacy:resident:1","old_family"));
assert(migrated.assignResidentHome("legacy:resident:2","old_family"));
assert.equal(migrated.villageHousing()[1].occupied,3);
assert(!migrated.assignResidentHome("legacy:resident:3","old_family"),"full huts never accept an extra occupant");
assert.equal(migrated.residentProfile("legacy:resident:3").resident.homeId,"camp");
assert.equal(migrated.data.village.population,5);
migrated.save();
const migratedAgain=new GameState({slot:2});
assert.deepEqual(migratedAgain.data.village.residents,migrated.data.village.residents);
const old=legacyResidents(4);
old[0].homeId="missing-hut";
const village={residents:normalizeResidents(old),buildings:[]};
normalizeHomes(village);
assert(village.residents.every(p=>p.homeId==="camp"),"missing homes migrate safely to available camp beds");
const duplicated=normalizeResidents([old[0],old[0]]);
assert.equal(duplicated.length,1,"bad saves cannot clone a named resident");
console.log("PASS Phase 3: individual residents, former clanmates, housemates, housing assignments, history, saves and succession");
