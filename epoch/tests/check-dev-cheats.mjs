import assert from "node:assert/strict";
import {GameState} from "../js/state.js";
import {DEV_CHEATS,newDevCheats} from "../js/dev-cheats.js";
import {SURVIVAL} from "../js/survival.js";
const records=new Map();
globalThis.localStorage={getItem:k=>records.get(k)||null,setItem:(k,v)=>records.set(k,v),removeItem:k=>records.delete(k)};
const g=new GameState({slot:1,newGame:true});
g.onChange=()=>{};g.onVitals=()=>{};
assert.deepEqual(g.devCheats,newDevCheats());
assert.equal(DEV_CHEATS.length,4);
assert.equal(g.setDevCheat("unknown",true),false);
assert.equal(g.setDevCheat("unlimitedHealth","true"),false);
g.data.survival.stamina=37;
assert(g.setDevCheat("unlimitedSprint",true));
assert(g.spendStamina(11,"sprint"));
assert.equal(g.data.survival.stamina,37,"free sprint does not consume stamina");
assert(g.sprintedThisTick,"sprinting still suppresses passive stamina regeneration");
assert(g.spendStamina(6,"gather"));
assert.equal(g.data.survival.stamina,37-6*SURVIVAL.staminaCostMultiplier,"gathering remains costly with unlimited sprint");
assert(g.setDevCheat("unlimitedSprint",false));
assert(g.spendStamina(11,"sprint"));
assert.equal(g.data.survival.stamina,(37-6*SURVIVAL.staminaCostMultiplier)-11*SURVIVAL.staminaCostMultiplier,"disabling immediately restores normal sprint costs");
g.data.survival.health=32;
assert(g.setDevCheat("unlimitedHealth",true));
assert.equal(g.data.survival.health,100);
assert.equal(g.damageHero(1000),false);
assert.equal(g.data.survival.health,100);
assert.equal(g.data.survival.deathCount,0);
assert(g.setDevCheat("unlimitedHealth",false));
assert(g.damageHero(19));
assert.equal(g.data.survival.health,81,"damage returns when health cheat is disabled");
g.data.survival.hunger=3;
assert(g.setDevCheat("unlimitedHunger",true));
assert.equal(g.data.survival.hunger,100);
g.advance(5);
assert.equal(g.data.survival.hunger,100,"hunger remains full after the normal survival tick");
assert(g.setDevCheat("unlimitedHunger",false));
g.advance(5);
assert(g.data.survival.hunger<100,"normal hunger drain resumes immediately");
g.data.survival.health=22;
assert(g.setDevCheat("neverDie",true));
assert(g.damageHero(10000));
assert.equal(g.data.survival.health,1,"never die keeps one health without filling the meter");
assert.equal(g.data.survival.gameOver,false);
// Start just before the new 432-second annual rollover.
g.data.hero.age=99;g.data.calendarProgress=1-1/432;
g.advance(2);
assert.equal(g.data.hero.age,100);
assert.equal(g.data.survival.gameOver,false,"age 100 is not fatal while never die is enabled");
g.save();
const saved=JSON.parse(records.get("epoch.stoneage.slot.1"));
assert.equal("devCheats" in saved,false,"developer switches never enter the slot save");
const reload=new GameState({slot:1});
assert.deepEqual(reload.devCheats,newDevCheats(),"cheats reset off on every session");
assert.equal(reload.data.hero.age,100);
reload.advance(1);
assert.equal(reload.data.survival.gameOver,true,"disabled cheat restores existing age cutoff");
assert.equal(reload.data.lastDeath.reason,"old age");
assert.equal(reload.setDevCheat("neverDie",true),false,"cannot resurrect game over slots");
const solo=new GameState({slot:2,newGame:true});
solo.data.survival.health=17;
assert(solo.setDevCheat("neverDie",true));
assert.equal(solo.heroDies("forced test"),false);
assert.equal(solo.data.survival.health,17);
assert(solo.setDevCheat("neverDie",false));
assert(solo.damageHero(1000,"a test injury"));
assert.equal(solo.data.survival.gameOver,true,"normal permadeath remains unchanged");
console.log("PASS dev cheats: free sprint only, injury immunity, hunger freeze, age-100 immunity, toggle reset and normal permadeath");
