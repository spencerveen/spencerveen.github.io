import assert from "node:assert/strict";
import {GameState} from "../js/state.js";
import {CRAFTING_PLANS} from "../js/equipment.js";
import {toolCondition,normalizeInventory} from "../js/inventory.js";
import {LEGACY_HOME} from "../js/stockpile.js";
const mem=new Map();
globalThis.localStorage={getItem:k=>mem.get(k)||null,setItem:(k,v)=>mem.set(k,v),removeItem:k=>mem.delete(k)};
const home=[LEGACY_HOME.x,LEGACY_HOME.z];
const game=new GameState({slot:1,newGame:true});game.onChange=()=>{};
assert(game.foundStockpile(...home));
const pile=game.data.village.stockpile.items;
pile.wood=30;pile.stone=30;pile.vines=10;pile.flint=10;
assert(!game.craftTool("stone_spear",...home),"spear gated by research");
assert(!game.craftTool("stone_axe",...home),"axe gated by research");
assert(!game.craftTool("wood_club",999,999),"remote crafting prohibited");
assert(!game.craftTool("bow",...home),"future recipes stay unavailable");
const before=JSON.stringify(pile);
assert(game.craftTool("wood_club",...home),"club craft available at founding");
assert.equal(game.data.equipment.weapon,"wood_club");
assert.deepEqual(game.equippedToolCondition(),{id:"wood_club",remaining:36,max:36});
assert.equal(pile.wood,27);
assert(!game.craftTool("wood_club",...home),"cannot duplicate owned club");
game.data.technologies.push("tools");
assert(game.craftTool("stone_axe",...home));
assert.equal(game.data.equipment.weapon,"wood_club");
assert.equal(game.inventoryCount("stone_axe"),1,"craft goes into backpack when hand occupied");
let index=game.data.inventory.findIndex(s=>s?.id==="stone_axe");
assert.equal(game.data.inventory[index].durability,45);
assert(game.equipFromPack(index));
assert.equal(game.data.equipment.weapon,"stone_axe");
assert.equal(game.equippedToolCondition().remaining,45);
assert.equal(game.data.inventory[index].id,"wood_club");
assert.equal(game.data.inventory[index].durability,36);
for(let n=0;n<5;n++)assert.equal(game.wearEquippedTool().remaining,44-n);
assert.equal(game.equippedToolCondition().remaining,40);
assert(game.equipFromPack(index));
assert.equal(game.equippedToolCondition().remaining,36);
assert.equal(game.data.inventory[index].durability,40);
game.save();
const loaded=new GameState({slot:1});
assert.equal(loaded.equippedToolCondition().remaining,36);
assert.equal(loaded.data.inventory[index].durability,40);
assert(loaded.equipFromPack(index));
assert.equal(loaded.equippedToolCondition().remaining,40);
assert(loaded.unequip("weapon"));
assert.equal(loaded.data.equipment.weapon,null);
assert.equal(loaded.data.weaponCondition,null);
assert(loaded.data.inventory.some(s=>s?.id==="stone_axe"&&s.durability===40));
assert(loaded.craftTool("stone_spear",...home));
assert.equal(loaded.data.equipment.weapon,"stone_spear");
assert.equal(loaded.equippedToolCondition().remaining,48);
assert.equal(game.data.village.stockpile.items.wood,25,"club and axe spend stored wood");
assert(JSON.stringify(pile)!==before,"valid craft changes supply counts");
const full=new GameState({slot:2,newGame:true});full.onChange=()=>{};
assert(full.foundStockpile(...home));
full.data.technologies.push("tools");
full.data.village.stockpile.items.wood=10;full.data.village.stockpile.items.stone=10;
full.data.equipment.weapon="wood_club";full.data.weaponCondition=12;
full.data.inventory=Array.from({length:10},()=>({id:"stone",qty:12}));
const stock=JSON.stringify(full.data.village.stockpile.items);
assert(!full.craftAxe(...home));
assert.equal(JSON.stringify(full.data.village.stockpile.items),stock);
assert.equal(full.equippedToolCondition().remaining,12);
const chop=new GameState({slot:3,newGame:true});chop.onChange=()=>{};
chop.data.equipment.weapon="stone_axe";chop.data.weaponCondition=1;chop.syncAxeOwnership();
const tree={resource:"wood",id:"tree:crafting-test"};
const chopped=chop.harvestResource(tree,"gather",1794600000000);
assert.equal(chopped.added,3);
assert(chopped.label.includes("Stone Axe broke"));
assert.equal(chop.data.equipment.weapon,null);
assert.equal(chop.data.weaponCondition,null);
assert(!chop.equippedAxe());
assert.equal(chop.harvestResource(tree,"gather",1794600001000).added,2);
assert.equal(toolCondition("stone_axe",999),45);
assert.equal(normalizeInventory([{id:"stone_axe",qty:1,durability:15}])[0].durability,15);
assert.equal(normalizeInventory([{id:"stone_axe",qty:1,durability:0}])[0],null);
assert.deepEqual(Object.keys(CRAFTING_PLANS).filter(id=>CRAFTING_PLANS[id].available).sort(),
 ["stone_axe","stone_spear","wood_club"]);
console.log("PASS Phase 5A crafting: research, stored resources, equipment, swaps, persistence, breakage, pack-full safety");
